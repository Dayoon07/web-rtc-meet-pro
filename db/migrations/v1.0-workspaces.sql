--   - chat_categories (새 테이블): 채널(그룹 채팅방)을 묶는 카테고리 = 부서. 예) "개발 연구소" 안에 #백오피스, #프론트오피스
--   - chat_rooms.category_id / sort_order: 채널이 속한 카테고리와 순서 (NULL = 카테고리 없음)
--   - subscriptions.team_id: 요금제가 적용되는 워크스페이스 (결제한 사람은 user_id)
--     기존 유료 구독은 그 사람이 만든 가장 오래된 워크스페이스로 옮긴다 (없으면 NULL = 적용 안 됨)
--   - payments.team_id, card_company, card_number_masked, approve_no: 영수증에 보여 줄 값
--   - plans: 채널(그룹 채팅방) 개수 제한 없음, 설명을 워크스페이스 기준으로
-- 실행 (저장소 루트에서):
--   PowerShell:  $env:NLS_LANG = "KOREAN_KOREA.AL32UTF8"
--   sqlplus limeet/limeet@//localhost:1521/XEPDB1 '@db/migrations/v1.0-workspaces.sql'

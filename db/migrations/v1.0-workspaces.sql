WHENEVER SQLERROR EXIT SQL.SQLCODE

-- 1. 카테고리
CREATE TABLE chat_categories (
    category_id         NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    name                VARCHAR2(50 CHAR) NOT NULL,
    sort_order          NUMBER(10)      DEFAULT 0 NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_chat_categories PRIMARY KEY (category_id),
    CONSTRAINT fk_chat_categories_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT ck_chat_categories_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_chat_categories_team ON chat_categories (team_id, sort_order);

ALTER TABLE chat_rooms ADD (
    category_id  NUMBER(19),
    sort_order   NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_chat_rooms_category FOREIGN KEY (category_id) REFERENCES chat_categories (category_id)
);

-- 2. 워크스페이스마다 요금제
ALTER TABLE subscriptions ADD (
    team_id  NUMBER(19),
    CONSTRAINT fk_subscriptions_team FOREIGN KEY (team_id) REFERENCES teams (team_id)
);
UPDATE subscriptions s
   SET team_id = (SELECT MIN(t.team_id) FROM teams t WHERE t.owner_id = s.user_id AND t.status = 'ACTIVE')
 WHERE s.status IN ('ACTIVE', 'PAST_DUE')
   AND s.plan_id IN (SELECT plan_id FROM plans WHERE code <> 'FREE');
DROP INDEX uidx_subscriptions_active;
-- 한 워크스페이스에 같은 플랜의 살아 있는 구독은 하나 (다른 플랜은 여러 개 가능, 가장 높은 플랜 적용)
CREATE UNIQUE INDEX uidx_subscriptions_active ON subscriptions (
    CASE WHEN status IN ('ACTIVE', 'PAST_DUE') AND team_id IS NOT NULL THEN team_id END,
    CASE WHEN status IN ('ACTIVE', 'PAST_DUE') AND team_id IS NOT NULL THEN plan_id END
);
CREATE INDEX idx_subscriptions_team ON subscriptions (team_id, status);

-- 3. 영수증
ALTER TABLE payments ADD (
    team_id             NUMBER(19),
    card_company        VARCHAR2(30 CHAR),
    card_number_masked  VARCHAR2(30),
    approve_no          VARCHAR2(30),
    CONSTRAINT fk_payments_team FOREIGN KEY (team_id) REFERENCES teams (team_id)
);
UPDATE payments p SET team_id = (SELECT s.team_id FROM subscriptions s WHERE s.subscription_id = p.subscription_id)
 WHERE p.subscription_id IS NOT NULL;
UPDATE payments p
   SET (card_company, card_number_masked) = (SELECT b.card_company, b.card_number_masked FROM billing_keys b WHERE b.billing_key_id = p.billing_key_id)
 WHERE p.billing_key_id IS NOT NULL;

-- 4. 플랜: 채널 제한 없음, 워크스페이스 기준 설명
UPDATE plans SET max_group_rooms_per_team = NULL;
UPDATE plans SET description = '가볍게 쓰는 모임·작은 팀'   WHERE code = 'FREE';
UPDATE plans SET description = '작은 워크스페이스'          WHERE code = 'PRO';
UPDATE plans SET description = '작은 회사 (녹화 포함)'      WHERE code = 'TEAM';
UPDATE plans SET description = '관리가 필요한 회사'         WHERE code = 'BUSINESS';

COMMIT;
PROMPT  카테고리, 워크스페이스별 요금제, 영수증 정보를 추가했어요.
EXIT

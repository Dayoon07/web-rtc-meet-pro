-- 앱 푸시(FCM) 기기: 앱 설치마다 토큰 하나. 같은 기기로 다른 사람이 로그인하면 같은 토큰의 행을 그 사람 것으로 바꾼다
CREATE TABLE push_devices (
    device_id           NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    platform            VARCHAR2(20)    NOT NULL,
    token               VARCHAR2(500)   NOT NULL,
    lang                VARCHAR2(10),                     -- 알림 문장 언어 (ko·en·ja·zh)
    user_agent          VARCHAR2(500),
    last_sent_at        TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_push_devices PRIMARY KEY (device_id),
    CONSTRAINT uk_push_devices_token UNIQUE (token),
    CONSTRAINT fk_push_devices_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_push_devices_platform CHECK (platform IN ('ANDROID')),
    CONSTRAINT ck_push_devices_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_push_devices_user ON push_devices (user_id);

COMMENT ON TABLE push_devices IS '앱 푸시(FCM) 기기 토큰';
COMMENT ON COLUMN push_devices.platform IS 'ANDROID';
COMMENT ON COLUMN push_devices.token IS 'FCM 등록 토큰 (앱을 다시 설치하거나 토큰이 바뀌면 새 행)';
COMMENT ON COLUMN push_devices.last_sent_at IS '마지막으로 푸시를 보낸 시각';


-- v1.1 → v1.2: AI 회의록 (받아쓰기 → 요약 → 결정 사항·할 일 → 채널에 올리기) + 실시간 자막 한도
--   - plans.ai_notes_minutes     : 한 달 동안 AI 회의록을 켤 수 있는 시간(분). 0 = 플랜에 없음
--   - plans.live_caption_minutes : 한 달 동안 실시간 자막·번역을 쓸 수 있는 시간(분). 0 = 없음 (Business 전용)
--   - meeting_notes       : 회의 하나의 AI 회의록 (켜고 끈 시간, 요약 결과)
--   - meeting_transcripts : 받아쓴 말 한 줄 = 1행 (말한 사람 브라우저가 받아써서 보낸다)
--   - ai_usages           : 워크스페이스·기능·달별 사용 시간(초)
--   - notifications.type 에 MEETING_NOTES_READY (회의록이 준비됨)
-- 실행 (저장소 루트에서):
--   PowerShell:  $env:NLS_LANG = "KOREAN_KOREA.AL32UTF8"
--   sqlplus limeet/limeet@//localhost:1521/XEPDB1 '@db/migrations/v1.2-ai-notes.sql'
-- =====================================================================
WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER TABLE plans ADD (
    ai_notes_minutes      NUMBER(10)  DEFAULT 0 NOT NULL,
    live_caption_minutes  NUMBER(10)  DEFAULT 0 NOT NULL
);
UPDATE plans SET ai_notes_minutes = 120  WHERE code = 'PRO';
UPDATE plans SET ai_notes_minutes = 600  WHERE code = 'TEAM';
UPDATE plans SET ai_notes_minutes = 3000, live_caption_minutes = 600 WHERE code = 'BUSINESS';

-- 회의 하나에 회의록 하나. 껐다 켜도 같은 행에 이어서 쌓는다
--   status: RECORDING(받아쓰는 중) / PAUSED(잠깐 끔) / PROCESSING(요약 중) / READY / FAILED / EMPTY(받아쓴 말이 없음)
CREATE TABLE meeting_notes (
    note_id             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    started_by          NUMBER(19)      NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'RECORDING' NOT NULL,
    active_since        TIMESTAMP(6),                          -- 지금 켜져 있으면 켠 시각
    active_seconds      NUMBER(10)      DEFAULT 0 NOT NULL,    -- 지금까지 켜져 있던 시간 합계
    title               VARCHAR2(200 CHAR),
    summary             CLOB,                                  -- JSON: {"summary":[...],"decisions":[...],"actionItems":[...]}
    language            VARCHAR2(10),
    model               VARCHAR2(60),
    error_message       VARCHAR2(500 CHAR),
    attempts            NUMBER(5)       DEFAULT 0 NOT NULL,
    generated_at        TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_meeting_notes PRIMARY KEY (note_id),
    CONSTRAINT uk_meeting_notes_meeting UNIQUE (meeting_id),
    CONSTRAINT fk_meeting_notes_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_notes_user FOREIGN KEY (started_by) REFERENCES users (user_id),
    CONSTRAINT ck_meeting_notes_status CHECK (status IN ('RECORDING', 'PAUSED', 'PROCESSING', 'READY', 'FAILED', 'EMPTY')),
    CONSTRAINT ck_meeting_notes_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_meeting_notes_status ON meeting_notes (status);

CREATE TABLE meeting_transcripts (
    transcript_id       NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    speaker_name        VARCHAR2(50 CHAR) NOT NULL,
    lang                VARCHAR2(10),
    content             VARCHAR2(2000 CHAR) NOT NULL,
    spoken_at           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_meeting_transcripts PRIMARY KEY (transcript_id),
    CONSTRAINT fk_meeting_transcripts_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_transcripts_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_meeting_transcripts_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_meeting_transcripts_meeting ON meeting_transcripts (meeting_id, spoken_at);

-- feature: NOTES(AI 회의록) / CAPTIONS(실시간 자막·번역). usage_month: 'YYYY-MM'
CREATE TABLE ai_usages (
    usage_id            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    feature             VARCHAR2(20)    NOT NULL,
    usage_month         VARCHAR2(7)     NOT NULL,
    used_seconds        NUMBER(12)      DEFAULT 0 NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_ai_usages PRIMARY KEY (usage_id),
    CONSTRAINT uk_ai_usages_team_month UNIQUE (team_id, feature, usage_month),
    CONSTRAINT fk_ai_usages_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT ck_ai_usages_feature CHECK (feature IN ('NOTES', 'CAPTIONS')),
    CONSTRAINT ck_ai_usages_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type CHECK (type IN (
    'TEAM_INVITATION', 'TEAM_INVITATION_ACCEPTED',
    'CHAT_ROOM_INVITED',
    'MEETING_SCHEDULED', 'MEETING_REMINDER', 'MEETING_STARTED', 'MEETING_CANCELED', 'MEETING_UPDATED',
    'MEETING_NOTES_READY',
    'PLAN_EXPIRING', 'PLAN_EXPIRED', 'PAYMENT_FAILED'
));

COMMIT;
PROMPT  AI 회의록(meeting_notes, meeting_transcripts, ai_usages)과 플랜 AI 한도를 추가했어요.
EXIT

-- v1.7: 브라우저 푸시 알림(웹 푸시) · 채널 알림 끄기 · 방해 금지 시간
--   sqlplus limeet/limeet@//localhost:1521/XEPDB1 '@db/migrations/v1.7-push-mute-dnd.sql'
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

-- 웹 푸시 구독: 브라우저(기기)마다 하나. endpoint 는 브라우저 회사(구글·모질라·애플)의 푸시 서버 주소
CREATE TABLE push_subscriptions (
    subscription_id     NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    endpoint            VARCHAR2(1000)  NOT NULL,
    p256dh              VARCHAR2(200)   NOT NULL,
    auth_secret         VARCHAR2(100)   NOT NULL,
    lang                VARCHAR2(10),
    user_agent          VARCHAR2(500),
    last_sent_at        TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_push_subscriptions PRIMARY KEY (subscription_id),
    CONSTRAINT uk_push_subscriptions_endpoint UNIQUE (endpoint),
    CONSTRAINT fk_push_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_push_subscriptions_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_push_subscriptions_user ON push_subscriptions (user_id);
COMMENT ON TABLE push_subscriptions IS '웹 푸시 구독 (브라우저를 닫아도 알림)';
COMMENT ON COLUMN push_subscriptions.lang IS '알림 문장 언어 (ko·en·ja·zh)';

-- 채널(방) 알림 끄기: 새 메시지 푸시를 보내지 않는다 (@멘션은 그래도 보낸다)
ALTER TABLE chat_room_members ADD (muted_yn CHAR(1) DEFAULT 'N' NOT NULL);
ALTER TABLE chat_room_members ADD CONSTRAINT ck_chat_room_members_muted_yn CHECK (muted_yn IN ('Y', 'N'));
COMMENT ON COLUMN chat_room_members.muted_yn IS '이 방 알림 끔';

-- 방해 금지 시간: 이 시간에는 푸시를 보내지 않는다 (알림 목록에는 그대로 쌓인다). 'HH:mm', 둘 다 NULL = 안 씀
ALTER TABLE users ADD (
    dnd_start      VARCHAR2(5),
    dnd_end        VARCHAR2(5),
    dnd_time_zone  VARCHAR2(50)
);
COMMENT ON COLUMN users.dnd_start IS '방해 금지 시작 (HH:mm, 사용자 시간대)';
COMMENT ON COLUMN users.dnd_end IS '방해 금지 끝 (HH:mm). 시작보다 이르면 다음 날까지';
COMMENT ON COLUMN users.dnd_time_zone IS '방해 금지 시간대 (예: Asia/Seoul)';

COMMIT;

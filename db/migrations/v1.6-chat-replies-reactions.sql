-- 이모지 반응: 한 사람이 한 메시지에 같은 이모지는 하나. 다시 누르면 deleted_yn 을 바꾼다
CREATE TABLE chat_message_reactions (
    reaction_id         NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    message_id          NUMBER(19)      NOT NULL,
    room_id             NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    emoji               VARCHAR2(64)    NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_chat_message_reactions PRIMARY KEY (reaction_id),
    CONSTRAINT uk_chat_message_reactions UNIQUE (message_id, user_id, emoji),
    CONSTRAINT fk_chat_message_reactions_message FOREIGN KEY (message_id) REFERENCES chat_messages (message_id),
    CONSTRAINT fk_chat_message_reactions_room FOREIGN KEY (room_id) REFERENCES chat_rooms (room_id),
    CONSTRAINT fk_chat_message_reactions_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_chat_message_reactions_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_chat_message_reactions_message ON chat_message_reactions (message_id);


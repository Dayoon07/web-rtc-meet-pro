-- v1.8: 팀 초대 링크 (링크만 있으면 팀에 들어온다. 비밀번호는 선택, 기간 제한 없음, 팀 소유자·관리자가 만들고 지운다)
--   NLS_LANG=KOREAN_KOREA.AL32UTF8 sqlplus limeet/limeet@//localhost:1521/XEPDB1 '@db/migrations/v1.8-team-invite-links.sql'
--   (NLS_LANG 이 UTF-8 이 아니면 한글 주석에서 ORA-01756 이 난다)
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

CREATE TABLE team_invite_links (
    invite_link_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    token               VARCHAR2(64)    NOT NULL,
    password_hash       VARCHAR2(100),
    created_by          NUMBER(19)      NOT NULL,
    join_count          NUMBER(10)      DEFAULT 0 NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_team_invite_links PRIMARY KEY (invite_link_id),
    CONSTRAINT uk_team_invite_links_token UNIQUE (token),
    CONSTRAINT fk_team_invite_links_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_team_invite_links_creator FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT ck_team_invite_links_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_team_invite_links_team ON team_invite_links (team_id, deleted_yn);
COMMENT ON TABLE team_invite_links IS '팀 초대 링크 (링크를 받은 사람은 누구든 팀에 들어온다)';
COMMENT ON COLUMN team_invite_links.token IS '초대 주소에 들어가는 무작위 값';
COMMENT ON COLUMN team_invite_links.password_hash IS '비밀번호 (BCrypt). NULL = 링크만으로 들어올 수 있음';
COMMENT ON COLUMN team_invite_links.created_by IS '만든 사람 (팀 소유자·관리자)';
COMMENT ON COLUMN team_invite_links.join_count IS '이 링크로 들어온 사람 수';

COMMIT;
PROMPT  팀 초대 링크 테이블을 추가했어요.
EXIT

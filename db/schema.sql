CREATE UNIQUE INDEX uidx_chat_rooms_direct ON chat_rooms (CASE WHEN direct_key IS NOT NULL THEN team_id END, direct_key);
CREATE INDEX idx_chat_rooms_team ON chat_rooms (team_id, room_type);


-- ---------------------------------------------------------------------
-- 7. 관리자 (관리자 사이트 전용. 서비스 사용자에게는 보이지 않는다)
-- ---------------------------------------------------------------------
-- 예상하지 못한 에러 1건 = 1행. 사용자 화면에는 error_code 만 보여 주고, 원인은 여기에만 남긴다.
--   error_code : ERR-YYYYMMDD-(UUID 20자리). 사용자가 문의할 때 알려 주는 값
--   source     : SERVER(서버 예외) / WEB(브라우저 화면 오류) / APP(Android·Windows 앱)
--   category   : DB_SCHEMA(테이블·컬럼 구조) / DB_CONSTRAINT(중복·필수값·참조 규칙) / DB_CONNECTION(DB 연결)
--                / DB_ETC / EXTERNAL(외부 연동) / CODE(소스 코드 버그) / CLIENT(화면 코드 오류) / NETWORK(화면이 서버에 연결 못 함)
--   user_id    : 에러를 만난 사용자 (로그인 전이면 NULL). 기록이 실패하지 않도록 FK 를 걸지 않는다
CREATE TABLE admin_error_logs (
    error_log_id        NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    error_code          VARCHAR2(40)    NOT NULL,
    source              VARCHAR2(10)    NOT NULL,
    category            VARCHAR2(30)    NOT NULL,
    exception_class     VARCHAR2(300),
    message             VARCHAR2(1000 CHAR),
    stack_trace         CLOB,
    http_method         VARCHAR2(10),
    request_path        VARCHAR2(1000),
    user_id             NUMBER(19),
    ip_address          VARCHAR2(45),
    user_agent          VARCHAR2(500),
    resolved_yn         CHAR(1)         DEFAULT 'N' NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_admin_error_logs PRIMARY KEY (error_log_id),
    CONSTRAINT uk_admin_error_logs_code UNIQUE (error_code),
    CONSTRAINT ck_admin_error_logs_source CHECK (source IN ('SERVER', 'WEB', 'APP')),
    CONSTRAINT ck_admin_error_logs_category CHECK (category IN (
        'DB_SCHEMA', 'DB_CONSTRAINT', 'DB_CONNECTION', 'DB_ETC', 'EXTERNAL', 'CODE', 'CLIENT', 'NETWORK'
    )),
    CONSTRAINT ck_admin_error_logs_resolved_yn CHECK (resolved_yn IN ('Y', 'N')),
    CONSTRAINT ck_admin_error_logs_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_admin_error_logs_created ON admin_error_logs (created_dt);
CREATE INDEX idx_admin_error_logs_category ON admin_error_logs (category, resolved_yn);

-- 관리자 사이트 "데이터 관리"에서 바꾼 기록. 행 1개를 고치거나 추가할 때마다 1행.
--   table_name : 바꾼 테이블 (소문자)
--   row_id     : 바꾼 행의 PK 값
--   action     : UPDATE / INSERT
--   changes    : 바뀐 컬럼별 이전 값 → 새 값 (JSON). 가려지는 컬럼(비밀번호 해시·토큰 등)은 고칠 수 없어서 남지 않는다
--   admin_id   : 바꾼 관리자 users.user_id (created_us 와 같다)
CREATE TABLE admin_data_changes (
    change_id           NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    table_name          VARCHAR2(128)   NOT NULL,
    row_id              VARCHAR2(100)   NOT NULL,
    action              VARCHAR2(10)    NOT NULL,
    changes             CLOB,
    admin_id            NUMBER(19)      NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_admin_data_changes PRIMARY KEY (change_id),
    CONSTRAINT ck_admin_data_changes_action CHECK (action IN ('UPDATE', 'INSERT')),
    CONSTRAINT ck_admin_data_changes_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_admin_data_changes_row ON admin_data_changes (table_name, row_id, created_dt);

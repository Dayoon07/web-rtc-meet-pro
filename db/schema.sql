-- =====================================================================
-- web-rtc-meet-pro  DB schema v0.4  (Oracle 19c+ / 23ai)
--   v0.4: 팀 채팅을 채널 → 채팅방(1:1 DIRECT / 1:N GROUP)으로, 회의 예약·초대(meeting_invitees), 알림(notifications)
--   v0.3: 회원 프로필(실명/전화/국가/출생년도/성별/약관 동의), 구글 로그인(user_social_accounts)
--
-- 그룹
--   1. 회원/인증      : users, user_social_accounts, refresh_tokens, login_histories
--   2. 플랜/구독/결제 : plans, subscriptions, billing_keys, payments
--   3. 팀            : teams, team_members, team_invitations
--   4. 팀 채팅        : chat_rooms, chat_room_members, chat_messages
--   5. 화상회의       : meetings, meeting_invitees, meeting_participants, meeting_events, meeting_recordings
--   6. 알림          : notifications
--
-- 규칙
--   - PK      : NUMBER(19) IDENTITY
--   - 불리언  : CHAR(1) 'Y'/'N'
--   - 상태값  : VARCHAR2 + CHECK (JPA EnumType.STRING)
--   - 시간    : TIMESTAMP(6), 서버 시간 기준
--   - 삭제    : 사용자 기록 보존을 위해 status / deleted_at 으로 소프트 삭제
--   - SFU 미디어 상태(Transport/Producer/Consumer)는 휘발성이라 DB에 넣지 않는다
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 회원 / 인증
-- ---------------------------------------------------------------------
-- 구글로만 가입한 사용자는 password_hash 가 NULL.
-- 실명 / 전화번호 / 국가 / 출생년도는 이메일 가입 시 필수, 구글 가입 시엔 첫 로그인 후 온보딩에서 채운다.
CREATE TABLE users (
    user_id            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    email              VARCHAR2(255)   NOT NULL,
    password_hash      VARCHAR2(100),
    nickname           VARCHAR2(50)    NOT NULL,
    real_name          VARCHAR2(50),
    phone_number       VARCHAR2(20),
    country_code       VARCHAR2(2),
    birth_year         NUMBER(4),
    gender             VARCHAR2(10),
    profile_image_url  VARCHAR2(500),
    terms_agreed_at    TIMESTAMP(6),
    marketing_agreed   CHAR(1)         DEFAULT 'N' NOT NULL,
    status             VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    last_login_at      TIMESTAMP(6),
    created_at         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at         TIMESTAMP(6),
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    CONSTRAINT ck_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_users_birth_year CHECK (birth_year BETWEEN 1900 AND 2100),
    CONSTRAINT ck_users_marketing CHECK (marketing_agreed IN ('Y', 'N'))
);

-- 소셜 로그인 연결 (구글). 같은 이메일의 기존 계정이 있으면 그 계정에 연결한다
CREATE TABLE user_social_accounts (
    social_account_id  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19)      NOT NULL,
    provider           VARCHAR2(20)    NOT NULL,
    provider_user_id   VARCHAR2(255)   NOT NULL,
    email              VARCHAR2(255),
    linked_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    last_login_at      TIMESTAMP(6),
    CONSTRAINT pk_user_social_accounts PRIMARY KEY (social_account_id),
    CONSTRAINT uk_user_social_accounts UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_user_social_accounts_user UNIQUE (user_id, provider),
    CONSTRAINT fk_user_social_accounts_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_user_social_accounts_provider CHECK (provider IN ('GOOGLE'))
);

-- 로그인 유지용 리프레시 토큰 (원문 대신 SHA-256 해시 저장)
CREATE TABLE refresh_tokens (
    refresh_token_id   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19)      NOT NULL,
    token_hash         VARCHAR2(64)    NOT NULL,
    ip_address         VARCHAR2(45),
    user_agent         VARCHAR2(500),
    expires_at         TIMESTAMP(6)    NOT NULL,
    revoked_at         TIMESTAMP(6),
    created_at         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (refresh_token_id),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

-- 로그인 시도 기록 (limeet-app 이 콘솔에만 찍던 IP / UA / ipinfo 위치)
CREATE TABLE login_histories (
    login_history_id   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19),
    email_attempted    VARCHAR2(255)   NOT NULL,
    login_method       VARCHAR2(20)    DEFAULT 'PASSWORD' NOT NULL,
    success            CHAR(1)         NOT NULL,
    failure_reason     VARCHAR2(50),
    ip_address         VARCHAR2(45),
    user_agent         VARCHAR2(500),
    country            VARCHAR2(2),
    city               VARCHAR2(100),
    created_at         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_login_histories PRIMARY KEY (login_history_id),
    CONSTRAINT fk_login_histories_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_login_histories_success CHECK (success IN ('Y', 'N')),
    CONSTRAINT ck_login_histories_method CHECK (login_method IN ('PASSWORD', 'GOOGLE'))
);
CREATE INDEX ix_login_histories_user ON login_histories (user_id, created_at);

-- ---------------------------------------------------------------------
-- 2. 플랜 / 구독 / 결제 (토스페이먼츠)
-- ---------------------------------------------------------------------
-- 플랜별 한도는 코드에 박지 않고 이 테이블에서 읽는다
CREATE TABLE plans (
    plan_id                NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    code                   VARCHAR2(20)    NOT NULL,
    name                   VARCHAR2(50)    NOT NULL,
    description            VARCHAR2(500),
    monthly_price          NUMBER(12)      DEFAULT 0 NOT NULL,
    max_owned_teams        NUMBER(10)      NOT NULL,
    max_members_per_team   NUMBER(10)      NOT NULL,
    max_group_rooms_per_team NUMBER(10)    NOT NULL,
    recording_enabled      CHAR(1)         DEFAULT 'N' NOT NULL,
    sort_order             NUMBER(10)      DEFAULT 0 NOT NULL,
    active                 CHAR(1)         DEFAULT 'Y' NOT NULL,
    created_at             TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at             TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_plans PRIMARY KEY (plan_id),
    CONSTRAINT uk_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_price CHECK (monthly_price >= 0),
    CONSTRAINT ck_plans_recording CHECK (recording_enabled IN ('Y', 'N')),
    CONSTRAINT ck_plans_active CHECK (active IN ('Y', 'N'))
);

-- 사용자 구독 이력. 회원가입 시 FREE 구독을 하나 만들고, 사용자당 ACTIVE 는 하나만.
CREATE TABLE subscriptions (
    subscription_id     NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    plan_id             NUMBER(19)      NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    auto_renew          CHAR(1)         DEFAULT 'N' NOT NULL,
    started_at          TIMESTAMP(6)    NOT NULL,
    current_period_end  TIMESTAMP(6),
    canceled_at         TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_subscriptions PRIMARY KEY (subscription_id),
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES plans (plan_id),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'CANCELED', 'EXPIRED', 'PAST_DUE')),
    CONSTRAINT ck_subscriptions_auto_renew CHECK (auto_renew IN ('Y', 'N'))
);
CREATE INDEX ix_subscriptions_user ON subscriptions (user_id, status);
CREATE UNIQUE INDEX ux_subscriptions_active ON subscriptions (CASE WHEN status = 'ACTIVE' THEN user_id END);

-- 토스페이먼츠 자동결제(빌링) 키. billing_key 는 애플리케이션에서 암호화해 저장
CREATE TABLE billing_keys (
    billing_key_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    customer_key        VARCHAR2(64)    NOT NULL,
    billing_key         VARCHAR2(500)   NOT NULL,
    card_company        VARCHAR2(30),
    card_number_masked  VARCHAR2(30),
    active              CHAR(1)         DEFAULT 'Y' NOT NULL,
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    revoked_at          TIMESTAMP(6),
    CONSTRAINT pk_billing_keys PRIMARY KEY (billing_key_id),
    CONSTRAINT uk_billing_keys_customer UNIQUE (customer_key),
    CONSTRAINT fk_billing_keys_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_billing_keys_active CHECK (active IN ('Y', 'N'))
);
CREATE INDEX ix_billing_keys_user ON billing_keys (user_id);

-- 결제 건. order_id 는 우리가 발급, payment_key 는 토스 승인 후 채움
CREATE TABLE payments (
    payment_id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    plan_id             NUMBER(19)      NOT NULL,
    subscription_id     NUMBER(19),
    billing_key_id      NUMBER(19),
    order_id            VARCHAR2(64)    NOT NULL,
    order_name          VARCHAR2(100)   NOT NULL,
    amount              NUMBER(12)      NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    method              VARCHAR2(30),
    payment_key         VARCHAR2(200),
    receipt_url         VARCHAR2(500),
    failure_code        VARCHAR2(100),
    failure_message     VARCHAR2(500),
    approved_at         TIMESTAMP(6),
    canceled_at         TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT uk_payments_key UNIQUE (payment_key),
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_payments_plan FOREIGN KEY (plan_id) REFERENCES plans (plan_id),
    CONSTRAINT fk_payments_subscription FOREIGN KEY (subscription_id) REFERENCES subscriptions (subscription_id),
    CONSTRAINT fk_payments_billing_key FOREIGN KEY (billing_key_id) REFERENCES billing_keys (billing_key_id),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('READY', 'DONE', 'CANCELED', 'FAILED', 'ABORTED'))
);
CREATE INDEX ix_payments_user ON payments (user_id, created_at);

-- ---------------------------------------------------------------------
-- 3. 팀
-- ---------------------------------------------------------------------
CREATE TABLE teams (
    team_id             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    owner_id            NUMBER(19)      NOT NULL,
    name                VARCHAR2(100)   NOT NULL,
    description         VARCHAR2(500),
    status              VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at          TIMESTAMP(6),
    CONSTRAINT pk_teams PRIMARY KEY (team_id),
    CONSTRAINT fk_teams_owner FOREIGN KEY (owner_id) REFERENCES users (user_id),
    CONSTRAINT ck_teams_status CHECK (status IN ('ACTIVE', 'DELETED'))
);
-- 플랜 한도 체크: 소유 팀 수
CREATE INDEX ix_teams_owner ON teams (owner_id, status);

CREATE TABLE team_members (
    team_member_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    role                VARCHAR2(20)    NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    joined_at           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    left_at             TIMESTAMP(6),
    CONSTRAINT pk_team_members PRIMARY KEY (team_member_id),
    CONSTRAINT uk_team_members UNIQUE (team_id, user_id),
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_team_members_role CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER')),
    CONSTRAINT ck_team_members_status CHECK (status IN ('ACTIVE', 'LEFT', 'KICKED'))
);
CREATE INDEX ix_team_members_user ON team_members (user_id, status);

-- 초대: 이메일로 보내고, 가입된 사용자면 invitee_id 도 채움
CREATE TABLE team_invitations (
    invitation_id       NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    inviter_id          NUMBER(19)      NOT NULL,
    invitee_email       VARCHAR2(255)   NOT NULL,
    invitee_id          NUMBER(19),
    token               VARCHAR2(64)    NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    expires_at          TIMESTAMP(6)    NOT NULL,
    responded_at        TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_team_invitations PRIMARY KEY (invitation_id),
    CONSTRAINT uk_team_invitations_token UNIQUE (token),
    CONSTRAINT fk_team_invitations_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_team_invitations_inviter FOREIGN KEY (inviter_id) REFERENCES users (user_id),
    CONSTRAINT fk_team_invitations_invitee FOREIGN KEY (invitee_id) REFERENCES users (user_id),
    CONSTRAINT ck_team_invitations_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'CANCELED'))
);
CREATE INDEX ix_team_invitations_team ON team_invitations (team_id, status);
CREATE INDEX ix_team_invitations_email ON team_invitations (invitee_email, status);

-- ---------------------------------------------------------------------
-- 4. 팀 채팅 (팀 > 채팅방 > 메시지)
--   DIRECT : 같은 팀 팀원끼리 1:1. 팀원이면 누구나 만들 수 있다
--   GROUP  : 1:N. 팀을 만든 사람(OWNER)만 만들 수 있고, 방 멤버가 다른 팀원을 초대할 수 있다
-- ---------------------------------------------------------------------
CREATE TABLE chat_rooms (
    room_id             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    room_type           VARCHAR2(10)    NOT NULL,
    name                VARCHAR2(100),
    -- DIRECT 방 중복 방지 키: "작은userId_큰userId"
    direct_key          VARCHAR2(50),
    created_by          NUMBER(19)      NOT NULL,
    last_message_at     TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at          TIMESTAMP(6),
    CONSTRAINT pk_chat_rooms PRIMARY KEY (room_id),
    CONSTRAINT fk_chat_rooms_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_chat_rooms_creator FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT ck_chat_rooms_type CHECK (room_type IN ('DIRECT', 'GROUP')),
    CONSTRAINT ck_chat_rooms_direct CHECK (
        (room_type = 'DIRECT' AND direct_key IS NOT NULL) OR (room_type = 'GROUP' AND direct_key IS NULL AND name IS NOT NULL)
    )
);
-- 팀 안에서 같은 두 사람의 1:1 방은 하나만 (GROUP 행은 두 컬럼이 모두 NULL 이라 제외됨)
CREATE UNIQUE INDEX ux_chat_rooms_direct ON chat_rooms (CASE WHEN direct_key IS NOT NULL THEN team_id END, direct_key);
CREATE INDEX ix_chat_rooms_team ON chat_rooms (team_id, room_type);

-- 방 참여자 + 마지막으로 읽은 메시지(안 읽은 개수 계산)
CREATE TABLE chat_room_members (
    room_member_id        NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    room_id               NUMBER(19)    NOT NULL,
    user_id               NUMBER(19)    NOT NULL,
    invited_by            NUMBER(19),
    last_read_message_id  NUMBER(19),
    joined_at             TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    left_at               TIMESTAMP(6),
    CONSTRAINT pk_chat_room_members PRIMARY KEY (room_member_id),
    CONSTRAINT uk_chat_room_members UNIQUE (room_id, user_id),
    CONSTRAINT fk_chat_room_members_room FOREIGN KEY (room_id) REFERENCES chat_rooms (room_id),
    CONSTRAINT fk_chat_room_members_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_chat_room_members_inviter FOREIGN KEY (invited_by) REFERENCES users (user_id)
);
CREATE INDEX ix_chat_room_members_user ON chat_room_members (user_id, left_at);

-- 메시지. SYSTEM 메시지(초대/퇴장 안내)는 sender_id 가 NULL
CREATE TABLE chat_messages (
    message_id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    room_id             NUMBER(19)      NOT NULL,
    sender_id           NUMBER(19),
    meeting_id          NUMBER(19),
    message_type        VARCHAR2(20)    DEFAULT 'TEXT' NOT NULL,
    content             VARCHAR2(4000)  NOT NULL,
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_at           TIMESTAMP(6),
    deleted_at          TIMESTAMP(6),
    CONSTRAINT pk_chat_messages PRIMARY KEY (message_id),
    CONSTRAINT fk_chat_messages_room FOREIGN KEY (room_id) REFERENCES chat_rooms (room_id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users (user_id),
    CONSTRAINT ck_chat_messages_type CHECK (message_type IN ('TEXT', 'SYSTEM'))
);
-- 커서 기반 페이지네이션 (room_id, message_id DESC)
CREATE INDEX ix_chat_messages_room ON chat_messages (room_id, message_id);
CREATE INDEX ix_chat_messages_meeting ON chat_messages (meeting_id);

-- ---------------------------------------------------------------------
-- 5. 화상회의 (mediasoup SFU 사이드카)
-- ---------------------------------------------------------------------
-- 바로 시작(LIVE) 또는 예약(SCHEDULED). 예약 회의는 시작 10분 전에 초대자에게 알림
CREATE TABLE meetings (
    meeting_id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    host_id             NUMBER(19)      NOT NULL,
    room_code           VARCHAR2(32)    NOT NULL,
    title               VARCHAR2(100)   NOT NULL,
    description         VARCHAR2(1000),
    status              VARCHAR2(20)    DEFAULT 'SCHEDULED' NOT NULL,
    scheduled_at        TIMESTAMP(6),
    duration_minutes    NUMBER(5)       DEFAULT 60 NOT NULL,
    reminder_sent_at    TIMESTAMP(6),
    started_at          TIMESTAMP(6),
    ended_at            TIMESTAMP(6),
    canceled_at         TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_meetings PRIMARY KEY (meeting_id),
    CONSTRAINT uk_meetings_room_code UNIQUE (room_code),
    CONSTRAINT fk_meetings_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_meetings_host FOREIGN KEY (host_id) REFERENCES users (user_id),
    CONSTRAINT ck_meetings_status CHECK (status IN ('SCHEDULED', 'LIVE', 'ENDED', 'CANCELED')),
    CONSTRAINT ck_meetings_duration CHECK (duration_minutes BETWEEN 5 AND 1440)
);
CREATE INDEX ix_meetings_team ON meetings (team_id, status);
-- 알림 스케줄러: SCHEDULED 이면서 아직 알림 안 보낸 회의를 시간순으로
CREATE INDEX ix_meetings_reminder ON meetings (status, scheduled_at, reminder_sent_at);

ALTER TABLE chat_messages ADD CONSTRAINT fk_chat_messages_meeting
    FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id);

-- 예약 회의 초대 대상 (팀원 중 선택). 주최자도 한 행으로 들어간다
CREATE TABLE meeting_invitees (
    invitee_id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_meeting_invitees PRIMARY KEY (invitee_id),
    CONSTRAINT uk_meeting_invitees UNIQUE (meeting_id, user_id),
    CONSTRAINT fk_meeting_invitees_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_invitees_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);
CREATE INDEX ix_meeting_invitees_user ON meeting_invitees (user_id);

-- 입장 1회 = 1행 (재입장 시 새 행). 접속 IP / UA 기록
CREATE TABLE meeting_participants (
    participant_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    display_name        VARCHAR2(50)    NOT NULL,
    ip_address          VARCHAR2(45),
    user_agent          VARCHAR2(500),
    joined_at           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    left_at             TIMESTAMP(6),
    leave_reason        VARCHAR2(20),
    CONSTRAINT pk_meeting_participants PRIMARY KEY (participant_id),
    CONSTRAINT fk_meeting_participants_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_participants_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_meeting_participants_reason CHECK (leave_reason IN ('LEFT', 'DISCONNECTED', 'KICKED', 'MEETING_ENDED'))
);
CREATE INDEX ix_meeting_participants_meeting ON meeting_participants (meeting_id, joined_at);
CREATE INDEX ix_meeting_participants_user ON meeting_participants (user_id, joined_at);

-- 화면공유 / 손들기 / 마이크·카메라 토글 / 녹화 시작·종료 등 회의 중 이벤트
CREATE TABLE meeting_events (
    event_id            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    user_id             NUMBER(19),
    event_type          VARCHAR2(30)    NOT NULL,
    payload             VARCHAR2(1000),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_meeting_events PRIMARY KEY (event_id),
    CONSTRAINT fk_meeting_events_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_events_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_meeting_events_type CHECK (event_type IN (
        'MEETING_STARTED', 'MEETING_ENDED',
        'SCREEN_SHARE_STARTED', 'SCREEN_SHARE_STOPPED',
        'HAND_RAISED', 'HAND_LOWERED',
        'MIC_ON', 'MIC_OFF', 'CAMERA_ON', 'CAMERA_OFF',
        'RECORDING_STARTED', 'RECORDING_STOPPED'
    ))
);
CREATE INDEX ix_meeting_events_meeting ON meeting_events (meeting_id, created_at);

-- 녹화 파일 (플랜 recording_enabled = 'Y' 일 때만)
CREATE TABLE meeting_recordings (
    recording_id        NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    meeting_id          NUMBER(19)      NOT NULL,
    started_by          NUMBER(19)      NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'RECORDING' NOT NULL,
    storage_url         VARCHAR2(1000),
    file_size_bytes     NUMBER(19),
    duration_seconds    NUMBER(10),
    started_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    ended_at            TIMESTAMP(6),
    CONSTRAINT pk_meeting_recordings PRIMARY KEY (recording_id),
    CONSTRAINT fk_meeting_recordings_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (meeting_id),
    CONSTRAINT fk_meeting_recordings_user FOREIGN KEY (started_by) REFERENCES users (user_id),
    CONSTRAINT ck_meeting_recordings_status CHECK (status IN ('RECORDING', 'PROCESSING', 'READY', 'FAILED', 'DELETED'))
);
CREATE INDEX ix_meeting_recordings_meeting ON meeting_recordings (meeting_id);

-- ---------------------------------------------------------------------
-- 6. 알림
--   문구는 저장하지 않고 type + params(JSON) 만 저장한다 → 클라이언트가 사용자 언어로 번역해서 표시
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
    notification_id     NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    type                VARCHAR2(40)    NOT NULL,
    params              VARCHAR2(2000),
    link                VARCHAR2(300),
    read_at             TIMESTAMP(6),
    created_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_notifications PRIMARY KEY (notification_id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'TEAM_INVITATION', 'TEAM_INVITATION_ACCEPTED',
        'CHAT_ROOM_INVITED',
        'MEETING_SCHEDULED', 'MEETING_REMINDER', 'MEETING_STARTED', 'MEETING_CANCELED'
    ))
);
CREATE INDEX ix_notifications_user ON notifications (user_id, read_at, notification_id);

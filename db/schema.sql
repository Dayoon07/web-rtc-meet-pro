    CONSTRAINT fk_chat_rooms_category FOREIGN KEY (category_id) REFERENCES chat_categories (category_id),
    CONSTRAINT ck_chat_rooms_type CHECK (room_type IN ('DIRECT', 'GROUP')),
    CONSTRAINT ck_chat_rooms_direct CHECK (
        (room_type = 'DIRECT' AND direct_key IS NOT NULL) OR (room_type = 'GROUP' AND direct_key IS NULL AND name IS NOT NULL)
    ),
    CONSTRAINT ck_chat_rooms_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);

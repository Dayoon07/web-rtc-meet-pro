-- =====================================================================
-- web-rtc-meet-pro  DB schema v0.8  (Oracle 19c+ / 21c XE / 23ai, 스키마(계정) 이름: limeet)
--   v0.8: 회의 고치기 알림(MEETING_UPDATED), 채팅 메시지 고친 시각(chat_messages.content_edited_at). 기존 DB 는 db/migrations/v0.8-edit-meetings-messages.sql
--   v0.7: 가입 이메일 인증(users.email_verified_at). 기존 DB 는 db/migrations/v0.7-email-verification.sql
--   v0.6: 관리자 사이트 데이터 관리의 변경 기록(admin_data_changes). 기존 DB 는 db/migrations/v0.6-admin-data-changes.sql
--   v0.5: 모든 테이블에 공통 컬럼 5개, 인덱스 이름 idx_ / uidx_, 채팅 첨부파일(chat_message_files),
--         관리자용 에러 기록(admin_error_logs), 사람이 입력하는 글자 컬럼을 CHAR 길이 기준으로,
--         시스템 관리자 역할(users.system_role)
--   v0.4: 팀 채팅을 채널 → 채팅방(1:1 DIRECT / 1:N GROUP)으로, 회의 예약·초대(meeting_invitees), 알림(notifications)
--   v0.3: 회원 프로필(실명/전화/국가/출생년도/성별/약관 동의), 구글 로그인(user_social_accounts)
--
-- 그룹
--   1. 회원/인증      : users, user_social_accounts, refresh_tokens, login_histories
--   2. 플랜/구독/결제 : plans, subscriptions, billing_keys, payments
--   3. 팀            : teams, team_members, team_invitations
--   4. 팀 채팅        : chat_rooms, chat_room_members, chat_messages, chat_message_files
--   5. 화상회의       : meetings, meeting_invitees, meeting_participants, meeting_events, meeting_recordings
--   6. 알림          : notifications
--   7. 관리자        : admin_error_logs, admin_data_changes  (관리자 사이트(별도 서브도메인)만 읽는다. 테이블 이름은 admin_ 으로 시작)
--
-- 공통 컬럼 (모든 테이블 맨 뒤 5개)
--   created_dt  생성일시     TIMESTAMP, 기본값 SYSTIMESTAMP
--   created_us  생성자       NUMBER(19), users.user_id (NULL = 시스템 또는 로그인 전: 회원가입·스케줄러·사이드카 콜백 등)
--   edited_dt   수정일시     TIMESTAMP, 처음엔 생성일시와 같음
--   edited_us   수정자       NUMBER(19), users.user_id (NULL = 시스템)
--   deleted_yn  사용/미사용  CHAR(1) 'Y'/'N', 기본값 'N' (소프트 삭제. 실제로 지우지 않는다)
--   * created_us / edited_us 는 일부러 FK 를 걸지 않는다 (관리자·시스템 작업도 기록해야 하고, 기록 때문에 저장이 실패하면 안 됨)
--
-- 이름 규칙
--   pk_테이블 / fk_테이블_대상 / uk_테이블_컬럼(유니크 제약) / ck_테이블_컬럼(체크 제약)
--   idx_테이블_컬럼(인덱스) / uidx_테이블_컬럼(유니크 인덱스)
--
-- 그 밖의 규칙
--   - PK      : NUMBER(19) IDENTITY
--   - 불리언  : CHAR(1) 'Y'/'N'
--   - 상태값  : VARCHAR2 + CHECK (JPA EnumType.STRING)
--   - 시간    : TIMESTAMP(6), 서버 시간 기준
--   - 글자    : 사람이 입력하는 값(이름·제목·내용)은 CHAR 기준 길이 (한글 1자 = 1). 코드·이메일·URL 은 BYTE
--   - SFU 미디어 상태(Transport/Producer/Consumer)는 휘발성이라 DB에 넣지 않는다
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 회원 / 인증
-- ---------------------------------------------------------------------
-- 구글로만 가입한 사용자는 password_hash 가 NULL.
-- email_verified_at: 이메일 주인임을 확인한 시각 (가입 인증 메일 링크 / 구글이 확인한 이메일). NULL 이면 받은 팀 초대를 볼 수 없다.
-- 실명 / 전화번호 / 국가 / 출생년도는 이메일 가입 시 필수, 구글 가입 시엔 첫 로그인 후 온보딩에서 채운다.
-- 탈퇴: status = 'DELETED' + deleted_yn = 'Y'
CREATE TABLE users (
    user_id            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    email              VARCHAR2(255)   NOT NULL,
    password_hash      VARCHAR2(100),
    email_verified_at  TIMESTAMP(6),
    nickname           VARCHAR2(50 CHAR)  NOT NULL,
    real_name          VARCHAR2(50 CHAR),
    phone_number       VARCHAR2(20),
    country_code       VARCHAR2(2),
    birth_year         NUMBER(4),
    gender             VARCHAR2(10),
    profile_image_url  VARCHAR2(500),
    terms_agreed_at    TIMESTAMP(6),
    marketing_agreed   CHAR(1)         DEFAULT 'N' NOT NULL,
    status             VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    last_login_at      TIMESTAMP(6),
    -- 서비스 전체 역할 (팀 안 역할과 별개): USER 일반 / ADMIN 관리자 사이트·관리자 API. 화면에서 바꾸지 않고 DB 에서 지정
    system_role        VARCHAR2(20)    DEFAULT 'USER' NOT NULL,
    created_dt         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us         NUMBER(19),
    edited_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us          NUMBER(19),
    deleted_yn         CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    CONSTRAINT ck_users_system_role CHECK (system_role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_users_birth_year CHECK (birth_year BETWEEN 1900 AND 2100),
    CONSTRAINT ck_users_marketing CHECK (marketing_agreed IN ('Y', 'N')),
    CONSTRAINT ck_users_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);

-- 소셜 로그인 연결 (구글). 같은 이메일의 기존 계정이 있으면 그 계정에 연결한다
CREATE TABLE user_social_accounts (
    social_account_id  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19)      NOT NULL,
    provider           VARCHAR2(20)    NOT NULL,
    provider_user_id   VARCHAR2(255)   NOT NULL,
    email              VARCHAR2(255),
    linked_at          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    last_login_at      TIMESTAMP(6),
    created_dt         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us         NUMBER(19),
    edited_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us          NUMBER(19),
    deleted_yn         CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_user_social_accounts PRIMARY KEY (social_account_id),
    CONSTRAINT uk_user_social_accounts UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_user_social_accounts_user UNIQUE (user_id, provider),
    CONSTRAINT fk_user_social_accounts_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_user_social_accounts_provider CHECK (provider IN ('GOOGLE')),
    CONSTRAINT ck_user_social_accounts_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);

-- 로그인 유지용 리프레시 토큰 (원문 대신 SHA-256 해시 저장)
CREATE TABLE refresh_tokens (
    refresh_token_id   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19)      NOT NULL,
    token_hash         VARCHAR2(64)    NOT NULL,
    ip_address         VARCHAR2(45),
    user_agent         VARCHAR2(500),
    expires_at         TIMESTAMP(6)    NOT NULL,
    revoked_at         TIMESTAMP(6),
    created_dt         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us         NUMBER(19),
    edited_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us          NUMBER(19),
    deleted_yn         CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (refresh_token_id),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_refresh_tokens_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

-- 로그인 시도 기록 (limeet-app 이 콘솔에만 찍던 IP / UA / ipinfo 위치). 시도 시각 = created_dt
CREATE TABLE login_histories (
    login_history_id   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id            NUMBER(19),
    email_attempted    VARCHAR2(255)   NOT NULL,
    login_method       VARCHAR2(20)    DEFAULT 'PASSWORD' NOT NULL,
    success            CHAR(1)         NOT NULL,
    failure_reason     VARCHAR2(50),
    ip_address         VARCHAR2(45),
    user_agent         VARCHAR2(500),
    country            VARCHAR2(2),
    city               VARCHAR2(100 CHAR),
    created_dt         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us         NUMBER(19),
    edited_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us          NUMBER(19),
    deleted_yn         CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_login_histories PRIMARY KEY (login_history_id),
    CONSTRAINT fk_login_histories_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_login_histories_success CHECK (success IN ('Y', 'N')),
    CONSTRAINT ck_login_histories_method CHECK (login_method IN ('PASSWORD', 'GOOGLE')),
    CONSTRAINT ck_login_histories_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_login_histories_user ON login_histories (user_id, created_dt);

-- ---------------------------------------------------------------------
-- 2. 플랜 / 구독 / 결제 (토스페이먼츠)
-- ---------------------------------------------------------------------
-- 플랜별 한도는 코드에 박지 않고 이 테이블에서 읽는다
CREATE TABLE plans (
    plan_id                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    code                     VARCHAR2(20)    NOT NULL,
    name                     VARCHAR2(50 CHAR)  NOT NULL,
    description              VARCHAR2(500 CHAR),
    monthly_price            NUMBER(12)      DEFAULT 0 NOT NULL,
    max_owned_teams          NUMBER(10)      NOT NULL,
    max_members_per_team     NUMBER(10)      NOT NULL,
    max_group_rooms_per_team NUMBER(10)      NOT NULL,
    recording_enabled        CHAR(1)         DEFAULT 'N' NOT NULL,
    sort_order               NUMBER(10)      DEFAULT 0 NOT NULL,
    active                   CHAR(1)         DEFAULT 'Y' NOT NULL,
    created_dt               TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us               NUMBER(19),
    edited_dt                TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us                NUMBER(19),
    deleted_yn               CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_plans PRIMARY KEY (plan_id),
    CONSTRAINT uk_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_price CHECK (monthly_price >= 0),
    CONSTRAINT ck_plans_recording CHECK (recording_enabled IN ('Y', 'N')),
    CONSTRAINT ck_plans_active CHECK (active IN ('Y', 'N')),
    CONSTRAINT ck_plans_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);

-- 사용자 구독 이력. 회원가입 시 FREE 구독을 하나 만들고, 사용자당 ACTIVE 는 하나만.
CREATE TABLE subscriptions (
    subscription_id     NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    plan_id             NUMBER(19)      NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    auto_renew          CHAR(1)         DEFAULT 'N' NOT NULL,
    started_at          TIMESTAMP(6)    NOT NULL,
    current_period_end  TIMESTAMP(6),
    canceled_at         TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_subscriptions PRIMARY KEY (subscription_id),
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES plans (plan_id),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'CANCELED', 'EXPIRED', 'PAST_DUE')),
    CONSTRAINT ck_subscriptions_auto_renew CHECK (auto_renew IN ('Y', 'N')),
    CONSTRAINT ck_subscriptions_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_subscriptions_user ON subscriptions (user_id, status);
CREATE UNIQUE INDEX uidx_subscriptions_active ON subscriptions (CASE WHEN status = 'ACTIVE' THEN user_id END);

-- 토스페이먼츠 자동결제(빌링) 키. billing_key 는 애플리케이션에서 암호화해 저장
CREATE TABLE billing_keys (
    billing_key_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    customer_key        VARCHAR2(64)    NOT NULL,
    billing_key         VARCHAR2(500)   NOT NULL,
    card_company        VARCHAR2(30 CHAR),
    card_number_masked  VARCHAR2(30),
    active              CHAR(1)         DEFAULT 'Y' NOT NULL,
    revoked_at          TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_billing_keys PRIMARY KEY (billing_key_id),
    CONSTRAINT uk_billing_keys_customer UNIQUE (customer_key),
    CONSTRAINT fk_billing_keys_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_billing_keys_active CHECK (active IN ('Y', 'N')),
    CONSTRAINT ck_billing_keys_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_billing_keys_user ON billing_keys (user_id);

-- 결제 건. order_id 는 우리가 발급, payment_key 는 토스 승인 후 채움
CREATE TABLE payments (
    payment_id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    user_id             NUMBER(19)      NOT NULL,
    plan_id             NUMBER(19)      NOT NULL,
    subscription_id     NUMBER(19),
    billing_key_id      NUMBER(19),
    order_id            VARCHAR2(64)    NOT NULL,
    order_name          VARCHAR2(100 CHAR) NOT NULL,
    amount              NUMBER(12)      NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    method              VARCHAR2(30 CHAR),
    payment_key         VARCHAR2(200),
    receipt_url         VARCHAR2(500),
    failure_code        VARCHAR2(100),
    failure_message     VARCHAR2(500 CHAR),
    approved_at         TIMESTAMP(6),
    canceled_at         TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT uk_payments_key UNIQUE (payment_key),
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_payments_plan FOREIGN KEY (plan_id) REFERENCES plans (plan_id),
    CONSTRAINT fk_payments_subscription FOREIGN KEY (subscription_id) REFERENCES subscriptions (subscription_id),
    CONSTRAINT fk_payments_billing_key FOREIGN KEY (billing_key_id) REFERENCES billing_keys (billing_key_id),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('READY', 'DONE', 'CANCELED', 'FAILED', 'ABORTED')),
    CONSTRAINT ck_payments_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_payments_user ON payments (user_id, created_dt);

-- ---------------------------------------------------------------------
-- 3. 팀
-- ---------------------------------------------------------------------
-- 삭제: status = 'DELETED' + deleted_yn = 'Y'
CREATE TABLE teams (
    team_id             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    owner_id            NUMBER(19)      NOT NULL,
    name                VARCHAR2(100 CHAR) NOT NULL,
    description         VARCHAR2(500 CHAR),
    status              VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_teams PRIMARY KEY (team_id),
    CONSTRAINT fk_teams_owner FOREIGN KEY (owner_id) REFERENCES users (user_id),
    CONSTRAINT ck_teams_status CHECK (status IN ('ACTIVE', 'DELETED')),
    CONSTRAINT ck_teams_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
-- 플랜 한도 체크: 소유 팀 수
CREATE INDEX idx_teams_owner ON teams (owner_id, status);

-- role: OWNER(팀을 만든 사람) / ADMIN / MEMBER. 역할별로 할 수 있는 일은 서버 TeamRole 한 곳에서 정한다
CREATE TABLE team_members (
    team_member_id      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    user_id             NUMBER(19)      NOT NULL,
    role                VARCHAR2(20)    NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    joined_at           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    left_at             TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_team_members PRIMARY KEY (team_member_id),
    CONSTRAINT uk_team_members UNIQUE (team_id, user_id),
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_team_members_role CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER')),
    CONSTRAINT ck_team_members_status CHECK (status IN ('ACTIVE', 'LEFT', 'KICKED')),
    CONSTRAINT ck_team_members_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_team_members_user ON team_members (user_id, status);

-- 초대: 이메일로 보내고, 가입된 사용자면 invitee_id 도 채움
CREATE TABLE team_invitations (
    invitation_id       NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    inviter_id          NUMBER(19)      NOT NULL,
    invitee_email       VARCHAR2(255)   NOT NULL,
    invitee_id          NUMBER(19),
    token               VARCHAR2(64)    NOT NULL,
    status              VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    expires_at          TIMESTAMP(6)    NOT NULL,
    responded_at        TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_team_invitations PRIMARY KEY (invitation_id),
    CONSTRAINT uk_team_invitations_token UNIQUE (token),
    CONSTRAINT fk_team_invitations_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
    CONSTRAINT fk_team_invitations_inviter FOREIGN KEY (inviter_id) REFERENCES users (user_id),
    CONSTRAINT fk_team_invitations_invitee FOREIGN KEY (invitee_id) REFERENCES users (user_id),
    CONSTRAINT ck_team_invitations_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'CANCELED')),
    CONSTRAINT ck_team_invitations_deleted_yn CHECK (deleted_yn IN ('Y', 'N'))
);
CREATE INDEX idx_team_invitations_team ON team_invitations (team_id, status);
CREATE INDEX idx_team_invitations_email ON team_invitations (invitee_email, status);

-- ---------------------------------------------------------------------
-- 4. 팀 채팅 (팀 > 채팅방 > 메시지 > 첨부파일)
--   DIRECT : 같은 팀 팀원끼리 1:1. 팀원이면 누구나 만들 수 있다
--   GROUP  : 1:N. 팀을 만든 사람(OWNER)만 만들 수 있고, 방 멤버가 다른 팀원을 초대할 수 있다
-- ---------------------------------------------------------------------
CREATE TABLE chat_rooms (
    room_id             NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    team_id             NUMBER(19)      NOT NULL,
    room_type           VARCHAR2(10)    NOT NULL,
    name                VARCHAR2(100 CHAR),
    -- DIRECT 방 중복 방지 키: "작은userId_큰userId"
    direct_key          VARCHAR2(50),
    created_by          NUMBER(19)      NOT NULL,
    last_message_at     TIMESTAMP(6),
    created_dt          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    created_us          NUMBER(19),
    edited_dt           TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    edited_us           NUMBER(19),
    deleted_yn          CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_chat_rooms PRIMARY KEY (room_id),
    CONSTRAINT fk_chat_rooms_team FOREIGN KEY (team_id) REFERENCES teams (team_id),
